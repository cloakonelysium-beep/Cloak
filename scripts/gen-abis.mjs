// Regenerates packages/sdk/src/abis.ts from the Foundry build output (run `forge build` first).
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
// Cloak v2: launches (config, factory, auction, token, vesting, the V2 seeder path the auction tests use) and drops.
// Gloam-side contracts (contracts-gloam) have their ABIs inline in the SDK.
const names = ["CloakConfig", "CloakFactory", "CloakAuction", "CloakToken", "CloakPair", "CloakVesting", "CloakVestingDeployer", "CloakSeeder", "CloakV2Market", "CloakFeeLocker", "CloakDrop", "CloakDropFactory", "CloakSpotBook", "CloakEscrowDrop", "CloakEscrowDropFactory"];
const fileOf = (n) => ({ CloakVestingDeployer: "CloakVesting.sol", CloakDropFactory: "CloakDrop.sol", CloakEscrowDropFactory: "CloakEscrowDrop.sol" })[n] ?? `${n}.sol`;
let out = "// Generated by scripts/gen-abis.mjs — do not edit.\n";
for (const n of names) {
  const { abi } = JSON.parse(readFileSync(`${root}contracts/out/${fileOf(n)}/${n}.json`, "utf8"));
  out += `\nexport const ${n === n.toUpperCase() ? n.toLowerCase() : n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
// Uniswap v4: Cloak's hook and market (contracts-v4), and the PoolManager built with Uniswap's settings
// GLOAK, the one private-only token (docs/GLOAK.md): the token and the maker the launch deployer's one-time door calls
const v4 = { CloakV4Hook: `${root}contracts-v4/out/CloakV4Hook.sol/CloakV4Hook.json`, CloakV4Market: `${root}contracts-v4/out/CloakV4Market.sol/CloakV4Market.json`, PoolManager: `${root}contracts-v4/out-uniswap/PoolManager.sol/PoolManager.json`, GloakToken: `${root}contracts-v4/out/GloakToken.sol/GloakToken.json`, GloakMaker: `${root}contracts-v4/out/GloakToken.sol/GloakMaker.json` };
for (const [n, file] of Object.entries(v4)) {
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  out += `\nexport const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(`${root}packages/sdk/src/abis.ts`, out);

// bytecode for deploy scripts / e2e
const bytecode = Object.fromEntries(
  names.map((n) => [n, JSON.parse(readFileSync(`${root}contracts/out/${fileOf(n)}/${n}.json`, "utf8")).bytecode.object]),
);
for (const [n, file] of Object.entries(v4)) bytecode[n] = JSON.parse(readFileSync(file, "utf8")).bytecode.object;
writeFileSync(`${root}packages/sdk/src/bytecode.ts`, `// Generated by scripts/gen-abis.mjs — do not edit.\nexport const bytecode = ${JSON.stringify(bytecode)} as const;\n`);
console.log("wrote abis.ts + bytecode.ts");
